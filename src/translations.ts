export function getTranslation(selectedLang: 'vi' | 'en' | 'lo' | 'zh') {
  const base = translations.vi;
  const target = (translations as any)[selectedLang] || base;
  if (selectedLang === 'vi') return base;

  const merge = (viObj: any, targetObj: any): any => {
    if (!targetObj) return viObj;
    const result: any = Array.isArray(targetObj) ? [...targetObj] : { ...targetObj };
    for (const key in viObj) {
      if (targetObj[key] === undefined || targetObj[key] === null) {
        result[key] = viObj[key];
      } else if (typeof viObj[key] === 'object' && viObj[key] !== null && !Array.isArray(viObj[key])) {
        result[key] = merge(viObj[key], targetObj[key]);
      }
    }
    return result;
  };

  return merge(base, target);
}
